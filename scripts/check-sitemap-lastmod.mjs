// Keeps <lastmod> honest: a sitemap entry should not claim a page was last
// touched in July when the page was rewritten in November.
//
// public/sitemap.xml is hand-maintained for static routes (the blog block is
// generated — see sync-blog.mjs). Nothing ever forced those dates to move when
// a page changed, so they drifted months behind the content and told crawlers
// the opposite of the truth.
//
// Three modes, deliberately different about what they touch:
//
//   (default)  Build mode. Corrects dist/sitemap.xml in place and logs what it
//              corrected. Never fails the build and never writes to public/ —
//              same rule as sync-blog.mjs, which keeps generated output out of
//              the tracked file so every content branch doesn't collide on it.
//   --check    Reports drift in public/sitemap.xml and exits 1. For running by
//              hand or in CI; nothing in the deploy path calls this.
//   --fix      Writes the corrected dates back into public/sitemap.xml.
//
// Scope, deliberately: this compares a ROUTE's own page file against its entry.
// It does not follow imports, so a change confined to a shared component — a
// nav item, a footer link, TrustBar on the homepage — will not be caught.
// Catching that would mean resolving the import graph per route and would then
// restamp every page on every shared-component edit, which is noise, not signal.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const routeDefsPath = path.join(root, "src", "routes", "routeDefs.ts");

const CHECK = process.argv.includes("--check");
const FIX = process.argv.includes("--fix");
const BUILD = !CHECK && !FIX;

const sitemapPath = BUILD
  ? path.join(root, "dist", "sitemap.xml")
  : path.join(root, "public", "sitemap.xml");

const git = (args) => execFileSync("git", args, { cwd: root }).toString().trim();

// A shallow clone has no file history to read, so every lookup would come back
// empty and the run would "pass" without having compared anything. Say so and
// leave the dates alone rather than reporting a clean result we didn't earn.
if (git(["rev-parse", "--is-shallow-repository"]) === "true") {
  console.log("check-sitemap-lastmod: shallow clone, no file history — skipped.");
  process.exit(0);
}

// A handful of routes take their title and description from the locale files
// rather than from their own page component, so the page file alone reports
// "unchanged" when the metadata a crawler cares about has in fact changed.
// (/ and /ta both render Index.tsx and read seo.home out of these.) Declared
// by hand on purpose — see the scope note above on why we don't walk imports.
const EXTRA_DEPS = {
  "/": ["src/i18n/locales/en.json"],
  "/ta": ["src/i18n/locales/ta.json"],
};

/** route path -> page source file, read from the single route table. */
function routeSources() {
  const src = fs.readFileSync(routeDefsPath, "utf-8");
  const out = new Map();
  const re = /path:\s*"(\/[^"]*)"\s*,\s*importer:\s*\(\)\s*=>\s*import\("([^"]+)"\)/g;
  for (const [, route, imp] of src.matchAll(re)) {
    if (route.startsWith("/blog")) continue; // generated by sync-blog.mjs
    const file = path.join(root, "src", "routes", imp) + ".tsx";
    if (fs.existsSync(file)) out.set(route, file);
  }
  return out;
}

/** Last commit date for a file (YYYY-MM-DD); today when it has uncommitted edits. */
const dateCache = new Map();
function lastChanged(file) {
  if (dateCache.has(file)) return dateCache.get(file);
  const dirty = git(["status", "--porcelain", "--", file]);
  const date = dirty
    ? new Date().toISOString().slice(0, 10)
    : git(["log", "-1", "--format=%cs", "--", file]) || null;
  dateCache.set(file, date);
  return date;
}

const sources = routeSources();
if (sources.size === 0) {
  throw new Error(
    "check-sitemap-lastmod: parsed no routes out of routeDefs.ts — the route " +
      "declaration shape has probably changed. Fix the pattern rather than " +
      "letting the check quietly compare nothing."
  );
}

let sitemap = fs.readFileSync(sitemapPath, "utf-8");
const stale = [];

for (const [route, file] of sources) {
  // Newest of the page file and anything else the route's metadata comes from.
  const dates = [file, ...(EXTRA_DEPS[route] ?? []).map((d) => path.join(root, d))]
    .map(lastChanged)
    .filter(Boolean);
  if (!dates.length) continue;
  const changed = dates.sort().at(-1);
  const escaped = route.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const entry = new RegExp(
    `(<loc>https://vasool\\.app${escaped}</loc>\\s*<lastmod>)([^<]*)(</lastmod>)`
  );
  const m = sitemap.match(entry);
  if (!m) continue; // whether every route HAS an entry is a separate concern
  if (m[2] < changed) {
    stale.push({ route, file: path.relative(root, file), was: m[2], now: changed });
    if (!CHECK) sitemap = sitemap.replace(entry, `$1${changed}$3`);
  }
}

const plural = (n) => (n === 1 ? "entry" : "entries");

if (CHECK) {
  if (!stale.length) {
    console.log(`check-sitemap-lastmod: ${sources.size} routes checked, all dates current.`);
    process.exit(0);
  }
  console.error(
    `\ncheck-sitemap-lastmod: ${stale.length} ${plural(stale.length)} in ` +
      `public/sitemap.xml ${stale.length === 1 ? "is" : "are"} older than the page described.\n`
  );
  for (const s of stale) {
    console.error(`  ${s.route}`);
    console.error(`      ${s.file} last changed ${s.now}, sitemap says ${s.was}`);
  }
  console.error(`\nFix: npm run sitemap:fix\n`);
  process.exit(1);
}

if (!stale.length) {
  console.log(`check-sitemap-lastmod: ${sources.size} routes checked, all dates current.`);
  process.exit(0);
}

fs.writeFileSync(sitemapPath, sitemap);
console.log(
  `check-sitemap-lastmod: corrected ${stale.length} stale ${plural(stale.length)} in ` +
    `${path.relative(root, sitemapPath)}.`
);
for (const s of stale) console.log(`  ${s.route}  ${s.was} -> ${s.now}`);
if (BUILD && stale.length) {
  console.log(
    "  (dist only — run `npm run sitemap:fix` to settle these in public/sitemap.xml)"
  );
}
